-- Админ базы без пароля, по unix-сокету: вход разрешён только процессу,
-- запущенному в контейнере базы от системного пользователя mysql, то есть
-- через `docker exec -u mysql`. Доступ к докеру на сервере и так равен root,
-- поэтому новой двери это не открывает, а пароль, который пришлось бы где-то
-- хранить ради бэкапа, сторожа и разворачивания, становится не нужен.
--
-- Приложение сюда не дотянется: оно ходит в базу по TCP, а сокет в его
-- контейнер не смонтирован. Выполняется один раз, при первом старте на пустом
-- томе.
--
-- Том базы уже был: скрипт не выполнится, и бэкап со сторожем получат отказ
-- доступа. Тогда один раз руками, паролем root из журнала первого старта:
--   docker logs <слаг>-mariadb 2>&1 | grep 'GENERATED ROOT PASSWORD'
--   docker exec -i <слаг>-mariadb mariadb -uroot -p < mariadb/initdb/00-socket-admin.sql
CREATE USER 'mysql'@'localhost' IDENTIFIED VIA unix_socket;
GRANT ALL PRIVILEGES ON *.* TO 'mysql'@'localhost' WITH GRANT OPTION;
