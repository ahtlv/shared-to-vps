#!/bin/sh
# Формат записей реестра и полнота матрицы прослеживаемости. Грабля без фазы
# означает дырку в конвейере, и это надо видеть до релиза, а не после.
# Записи живут в реестре ядра и в adapters/*/gotchas.md, нумерация общая:
# G-1NN ядро, G-2NN и выше адаптеры. Реестр адаптерные записи не дублирует,
# а перечисляет ссылкой, и каждая обязана там встретиться.
set -u
cd "$(dirname "$0")/.."
fails=0
fail() { printf 'FAIL  %s\n' "$1" >&2; fails=$((fails + 1)); }

reg=references/90-gotchas.md
[ -f "$reg" ] || { echo "нет реестра $reg" >&2; exit 1; }

files="$reg $(ls adapters/*/gotchas.md 2>/dev/null | tr '\n' ' ')"

ids=
for f in $files; do
    fids=$(grep -o '^### G-[0-9][0-9][0-9]' "$f" | awk '{print $2}')
    [ -n "$fids" ] || fail "${f}: нет записей вида \"### G-NNN\""
    ids="$ids
$fids"
done
ids=$(printf '%s\n' "$ids" | sed '/^$/d')

# Уникальность номеров по всем файлам сразу.
dups=$(printf '%s\n' "$ids" | sort | uniq -d)
[ -z "$dups" ] || fail "повторяющиеся номера: $dups"

# Обязательные поля у каждой записи, в своём файле.
for f in $files; do
    for id in $(grep -o '^### G-[0-9][0-9][0-9]' "$f" | awk '{print $2}'); do
        body=$(awk -v id="$id" '$0 ~ "^### " id " " {flag=1; next} /^#/{flag=0} flag' "$f")
        for field in 'Симптом' 'Что происходит' 'Почему' 'Чем закрыто' 'Фаза' 'Кейс'; do
            printf '%s\n' "$body" | grep -qF -- "- **$field:**" || fail "${id}: нет поля «${field}»"
        done
    done
done

# Индекс в начале реестра и ссылки адаптерных записей.
grep -q '^## Индекс по симптомам' "$reg" || fail 'в реестре нет раздела "Индекс по симптомам"'
first=$(grep -n '^### G-' "$reg" | head -1 | cut -d: -f1)
idx=$(grep -n '^## Индекс по симптомам' "$reg" | head -1 | cut -d: -f1)
[ -z "$first" ] || [ -z "$idx" ] || [ "$idx" -lt "$first" ] || fail 'индекс стоит после первой записи'
for id in $ids; do
    grep -qF "$id" "$reg" || fail "${id} не упомянут в реестре ядра"
done
for ref in $(sed -n '/^## Индекс по симптомам/,/^## /p' "$reg" | grep -o 'G-[0-9][0-9][0-9]' | sort -u); do
    printf '%s\n' "$ids" | grep -qx "$ref" || fail "индекс ссылается на несуществующую ${ref}"
done

# Полнота матрицы: у каждого номера своя строка таблицы. Упоминания в прозе
# мало: номер из пояснения к «не ловится» иначе засчитал бы удалённую строку.
matrix=cases/traceability.md
if [ -f "$matrix" ]; then
    for id in $ids; do
        grep -q "^| $id |" "$matrix" || fail "${id} отсутствует в матрице прослеживаемости"
    done
    # Строка без ворот или «нет» без причины это тот же скрытый пропуск.
    # Колонки: запись, симптом, фаза, ворота, кейс, чем закрыто, ловится.
    bad=$(awk -F'|' '/^\| G-[0-9][0-9][0-9] \|/ {
        for (i = 2; i < NF; i++) gsub(/^ +| +$/, "", $i)
        if (NF != 9) { print $2 ": ожидается 7 колонок, найдено " NF - 2; next }
        if ($5 == "") print $2 ": пустая колонка «Ворота»"
        if ($8 !~ /^(ворота|адаптер|частично|нет)$/) print $2 ": «Ловится» не из набора ворота/адаптер/частично/нет: " $8
        if ($8 == "нет" && $5 !~ /^не ловится/) print $2 ": «нет» без строки «не ловится …» в колонке «Ворота»"
    }' "$matrix")
    # Здесь-документ, а не конвейер: в конвейере `while` идёт в подоболочке, и
    # увеличенный счётчик до кода возврата не доедет.
    if [ -n "$bad" ]; then
        while IFS= read -r line; do fail "$line"; done <<EOF
$bad
EOF
    fi
else
    fail "нет матрицы $matrix"
fi

[ "$fails" -eq 0 ] || { echo "реестр: $fails нарушений" >&2; exit 1; }
echo 'реестр: формат и матрица в порядке'
